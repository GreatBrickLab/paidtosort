#!/usr/bin/env python3
"""Build Alpha 2's static data from Inventory Research's parts.db (opened read-only, never written).
-> site/alpha2/data/weights.json  {part: grams}   (the app applies the 0.85 low factor)
-> lib/alpha2/prices.js           {"part|color": [used avg $, thin_sales]}  (server-side only, used in the CSV export)"""
import json, sqlite3
DB = "/workspace/gbl/paidtosort-parts-data/parts.db"
c = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
W = {p: round(float(w), 3) for p, w in c.execute("select part_id, weight_g from parts where weight_g is not null and weight_g != '' and cast(weight_g as real) > 0")}
P = {f"{p}|{col}": [round(float(v), 4), int(t or 0)] for p, col, v, t in c.execute("select part_id, color_id, price_used_avg, thin_sales from part_colors where price_used_avg is not null and price_used_avg != ''")}
json.dump(W, open("site/alpha2/data/weights.json", "w"), separators=(",", ":"), sort_keys=True)
open("lib/alpha2/prices.js", "w").write("// generated by scripts/build_data.py from parts.db (Inventory Research); used-condition average $, thin_sales flag\nexport default " + json.dumps(P, separators=(",", ":"), sort_keys=True) + ";\n")
print(len(W), "weights;", len(P), "part+color prices")
